#!/usr/bin/env python3
"""List every painted effect picture (assets/fx/<hero>/*.webp) into fx_manifest.js for the in-game effect editor.
Re-run after adding pictures: python3 tools/fx_manifest.py"""
import os,json
root=os.path.join(os.path.dirname(__file__),'..');d=os.path.join(root,'assets','fx');out={}
for h in sorted(os.listdir(d)):
  p=os.path.join(d,h)
  if os.path.isdir(p):out[h]=sorted(f[:-5] for f in os.listdir(p) if f.endswith('.webp'))
open(os.path.join(root,'fx_manifest.js'),'w').write('/* generated by tools/fx_manifest.py */\nwindow.FX_PICS='+json.dumps(out,separators=(',',':'))+';\n')
print({k:len(v) for k,v in out.items()})
