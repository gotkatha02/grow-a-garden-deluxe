"""Build skill_shapes.js — the hit area of every active skill, for the mobile aim indicator.
Usage (server running on :8765):  python3 tools/skill_shapes.py [hero ...]
For each hero: open the game in test mode (Lv 99, every skill), run tools/skill_shapes_probe.js in the empty arena,
fit a shape to the dummies each skill hit (hero at 0,0 facing +x) and merge the result into skill_shapes.js.
Shapes:  cone {k,r,h(half angle rad)} · line {k,len,w} · self {k,r} (circle around the hero) · aim {k} (ground circle,
radius from the skill's own radius()) · target {k} (single target) · none (buffs, no hit)."""
import asyncio, json, math, os, re, sys
from playwright.async_api import async_playwright
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEROES=['wolf','rhino','owl','jaguar','croc','axolotl','cat','hippo','sheep','dragon','lion','kitsune','bastet','anubis','raven','wukong']
TGT=(70,0)

# shapes the probe cannot see (dashes, summons, swarm orders — the monkey's clones hit for them): set by hand, applied after the fit
FIX={'wukong':{'gnCloud':{'k':'line','len':300,'w':40},'gaLeap':{'k':'target'},'gbBlow':{'k':'target'},'gbForm':{'k':'none'},'gbRecall':{'k':'none'},
     'gbMob':{'k':'target'},'gxBang':{'k':'target'},'gxStorm':{'k':'self','r':130}}}

def fit(v):
    hit=v['hit']
    if v['type']=='ground': return {'k':'aim'}
    if not hit: return {'k':'none'}
    if len(hit)<=3: return {'k':'target'}                       # one enemy (the target, or the nearest one)
    far=[(x,y) for x,y in hit if math.hypot(x,y)>30] or hit
    d=[math.hypot(x,y) for x,y in hit]; R=max(d)
    ang=[abs(math.atan2(y,x)) for x,y in far]
    if max(ang)>2.4: return {'k':'self','r':round(R)}           # reaches behind the hero → circle around the hero
    xs=[x for x,y in hit]; ys=[abs(y) for x,y in hit]
    if min(xs)>-25 and max(ys)<=max(45,.32*max(xs)): return {'k':'line','len':round(max(xs)),'w':round(2*max(ys)+20)}
    return {'k':'cone','r':round(R),'h':round(min(math.pi,max(ang)+.08),2)}

async def probe(ch):
    async with async_playwright() as p:
        b=await p.chromium.launch(args=["--use-gl=swiftshader"]);pg=await b.new_page(viewport={'width':900,'height':600})
        await pg.goto(f'http://localhost:8765/index.html?char={ch}&map=snowpine');await pg.wait_for_timeout(4000)
        await pg.evaluate("[...document.querySelectorAll('button')].find(b=>/โหมดทดสอบ/.test(b.textContent))?.click()");await pg.wait_for_timeout(5000)
        await pg.add_script_tag(path=os.path.join(ROOT,'tools/skill_shapes_probe.js'))
        await pg.evaluate("mapTest.enterMap(null,null)");await pg.wait_for_timeout(500)
        r=await pg.evaluate("probeSkillShapes()");await b.close();return r

def main():
    heroes=sys.argv[1:] or HEROES; path=os.path.join(ROOT,'skill_shapes.js'); data={}
    if os.path.exists(path):
        m=re.search(r'window\.SKILL_SHAPES=(\{.*\});',open(path,encoding='utf-8').read(),re.S)
        if m: data=json.loads(m.group(1))
    for ch in heroes:
        r=asyncio.run(probe(ch)); data[ch]={k:fit(v) for k,v in r.items()}; data[ch].update(FIX.get(ch,{}))
        print(ch,{k:s['k'] for k,s in data[ch].items()},flush=True)
        open(path,'w',encoding='utf-8').write('/* Skill hit areas for the mobile aim indicator — generated by tools/skill_shapes.py (do not edit by hand; re-run after changing a skill).\n'
          '   cone {r,h} · line {len,w} · self {r} · aim (ground circle, radius from SKILLS[k].radius()) · target · none.  Units = world px, hero at 0,0 facing +x. */\n'
          'window.SKILL_SHAPES='+json.dumps(data,separators=(',',':'))+';\n')
main()
