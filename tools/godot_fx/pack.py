"""Pack Godot-rendered frames into a webp flipbook sheet for the game.
usage: python -X utf8 -I tools/godot_fx/pack.py RAW_DIR NAME [ss=2] [trim=1] [ax=X ay=Y] [q=90] [extra=json]
  RAW_DIR  frames 000.png … from render.gd (premultiplied colour, ss× size)
  NAME     -> assets/fx/wolf_gd/NAME.webp + entry NAME in assets/fx/wolf_gd/meta.js (window.WGX_META)
  ax, ay   anchor in OUTPUT px of the untrimmed frame (ground point / centre); kept valid after trimming
  extra    JSON merged into the meta entry (fps, ref sizes, segments …)
Also writes RAW_DIR/../NAME_preview.png (frames on dark + light ground) for checking."""
import sys, os, json, math, re
from PIL import Image
import numpy as np

raw, name = sys.argv[1], sys.argv[2]
FM = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'fx_meta.json'), encoding='utf-8')).get(name, {})
opt = {k: (json.dumps(v) if k == 'extra' else str(v)) for k, v in FM.items()}   # fx_meta.json first, command line overrides
opt.update(dict(a.split('=', 1) for a in sys.argv[3:]))
ss = int(opt.get('ss', 2)); trim = opt.get('trim', '1') == '1'; q = int(opt.get('q', 90))
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT = os.path.join(ROOT, 'assets', 'fx', 'wolf_gd'); os.makedirs(OUT, exist_ok=True)

files = sorted(f for f in os.listdir(raw) if f.endswith('.png'))
frames = []
for f in files:
    A = np.asarray(Image.open(os.path.join(raw, f)).convert('RGBA')).astype(np.float32)
    a = A[..., 3:4] / 255.0
    rgb = np.where(a > 1e-3, A[..., :3] / np.maximum(a, 1e-3), 0)          # un-premultiply
    im = Image.fromarray(np.dstack([np.clip(rgb, 0, 255), A[..., 3:4]]).astype(np.uint8), 'RGBA')
    # premultiplied down-scale (no dark fringes), then back to straight alpha
    P = np.asarray(im).astype(np.float32); P[..., :3] *= P[..., 3:4] / 255.0
    W, H = im.width // ss, im.height // ss
    ch = [Image.fromarray(P[..., c].astype(np.float32), 'F').resize((W, H), Image.LANCZOS) for c in range(4)]
    Q = np.dstack([np.asarray(c) for c in ch]); al = np.clip(Q[..., 3:4], 0, 255)
    Q[..., :3] = np.where(al > .5, Q[..., :3] * 255.0 / np.maximum(al, 1e-3), 0)
    frames.append(np.clip(np.dstack([Q[..., :3], al]), 0, 255).astype(np.uint8))
H, W = frames[0].shape[:2]
x0, y0, x1, y1 = 0, 0, W, H
if trim:
    m = np.zeros((H, W), bool)
    for F in frames: m |= F[..., 3] > 3
    ys, xs = np.nonzero(m)
    if len(xs): x0, y0, x1, y1 = int(max(0, xs.min() - 2)), int(max(0, ys.min() - 2)), int(min(W, xs.max() + 3)), int(min(H, ys.max() + 3))
fw, fh = x1 - x0, y1 - y0
n = len(frames); cols = int(opt.get('cols', 0)) or max(1, min(n, int(math.ceil(math.sqrt(n * fh / fw)))))
rows = int(math.ceil(n / cols))
sheet = Image.new('RGBA', (cols * fw, rows * fh), (0, 0, 0, 0))
for i, F in enumerate(frames):
    sheet.paste(Image.fromarray(F[y0:y1, x0:x1], 'RGBA'), ((i % cols) * fw, (i // cols) * fh))
dst = os.path.join(OUT, name + '.webp'); sheet.save(dst, 'WEBP', quality=q, method=6, alpha_quality=95)
ax = float(opt.get('ax', W / 2)) - x0; ay = float(opt.get('ay', H / 2)) - y0
ent = {'n': n, 'cols': cols, 'w': fw, 'h': fh, 'ax': round(ax, 1), 'ay': round(ay, 1), 'full': [W, H]}
if 'extra' in opt: ent.update(json.loads(opt['extra']))
mp = os.path.join(OUT, 'meta.js'); meta = {}
if os.path.exists(mp):
    s = open(mp, encoding='utf-8').read(); mm = re.search(r'window\.WGX_META=(\{.*\});', s, re.S)
    if mm: meta = json.loads(mm.group(1))
meta[name] = ent
txt = '/* generated by tools/godot_fx/pack.py — Godot-rendered wolf effect flipbooks (see tools/godot_fx/README_TH.md) */\nwindow.WGX_META=' + json.dumps(dict(sorted(meta.items())), separators=(',', ':')) + ';\n'
open(mp, 'w', encoding='utf-8', newline='\n').write(txt)   # built first: a failed dump must not truncate the file
# preview: every frame on dark and on snow-white ground
pv = Image.new('RGB', (n * fw, fh * 2), (30, 34, 44)); pv.paste((236, 240, 246), (0, fh, n * fw, fh * 2))
for i, F in enumerate(frames):
    t = Image.fromarray(F[y0:y1, x0:x1], 'RGBA'); pv.paste(t, (i * fw, 0), t); pv.paste(t, (i * fw, fh), t)
pv.save(os.path.join(os.path.dirname(os.path.abspath(raw)), name + '_preview.png'))
print(f'{name}: {n} frames {fw}x{fh} sheet {sheet.width}x{sheet.height} {os.path.getsize(dst)//1024} KB anchor ({ax:.0f},{ay:.0f})')
